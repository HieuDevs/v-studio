SR = 44_100
GEN_VERSION = 1
TARGET_RMS = 0.1                 # −20 dBFS: every track sits at the same loudness
MAX_UPLOAD = 200 * 1024 * 1024
MAX_USER_SECONDS = 20 * 60
_USER_ID = re.compile(r"^u-[a-f0-9]{12}$")
_LOCK = threading.RLock()


def music_dir() -> Path:
    return app_home() / "music"


# ── synthesis helpers ────────────────────────────────────────────────────────
# Everything is built on a circular buffer (notes that run past the end wrap to
# the start, filters/reverb are circular FFT convolutions), so the end of a
# track flows straight into its beginning and the mixer can loop it forever.

def _mtof(m: float) -> float:
    return 440.0 * 2.0 ** ((m - 69) / 12)


def _place(buf: np.ndarray, start: int, sig: np.ndarray) -> None:
    n = len(buf)
    start %= n
    while len(sig):
        k = min(len(sig), n - start)
        buf[start:start + k] += sig[:k]
        sig, start = sig[k:], 0


def _spectral(x: np.ndarray, gain: Callable[[np.ndarray], np.ndarray]) -> np.ndarray:
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    return np.fft.irfft(np.fft.rfft(x) * gain(f), n)


def _lowpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    return _spectral(x, lambda f: 1 / np.sqrt(1 + (f / cutoff) ** (2 * order)))


def _highpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    return _spectral(x, lambda f: 1 / np.sqrt(1 + (cutoff / np.maximum(f, 1e-3)) ** (2 * order)))


def _reverb(x: np.ndarray, seconds: float, mix: float, seed: int, damp: float = 5000.0) -> np.ndarray:
    n = len(x)
    rng = np.random.default_rng(seed)
    m = min(int(seconds * SR), n)
    t = np.arange(m) / SR
    ir = rng.standard_normal(m) * np.exp(-t * 6.9 / seconds)     # −60 dB after `seconds`
    ramp = int(0.012 * SR)
    ir[:ramp] *= np.linspace(0, 1, ramp)
    wet = np.fft.irfft(np.fft.rfft(x) * np.fft.rfft(ir, n), n)
    wet = _lowpass(wet, damp)
    wet *= np.sqrt(np.mean(x ** 2) / max(float(np.mean(wet ** 2)), 1e-12))
    return (1 - mix) * x + mix * wet


def _env(n: int, attack: float, release: float) -> np.ndarray:
    e = np.ones(n)
    a, r = min(int(attack * SR), n), min(int(release * SR), n)
    if a:
        e[:a] = np.linspace(0, 1, a)
    if r:
        e[n - r:] *= np.linspace(1, 0, r)
    return e


def _piano(freq: float, dur: float, vel: float, rng) -> np.ndarray:
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for h, a in enumerate((1.0, 0.42, 0.22, 0.11, 0.06, 0.035), start=1):
        f = freq * h * (1 + 0.0004 * h * h)                      # slight string inharmonicity
        if f > SR / 2 - 2000:
            break
        decay = np.exp(-t * (0.9 + 0.55 * h) * (freq / 440) ** 0.35)
        out += a * np.sin(2 * np.pi * f * t + rng.uniform(0, 2 * np.pi)) * decay
    return out * _env(n, 0.004, 0.12) * vel


def _pluck(freq: float, dur: float, vel: float, rng) -> np.ndarray:
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for h, a in enumerate((1.0, 0.5, 0.3, 0.16, 0.08), start=1):
        out += a * np.sin(2 * np.pi * freq * h * t + rng.uniform(0, 6.28)) * np.exp(-t * (5 + 3 * h))
    return out * _env(n, 0.003, 0.05) * vel


def _rhodes(freq: float, dur: float, vel: float, rng) -> np.ndarray:
    n = int(dur * SR)
    t = np.arange(n) / SR
    body = np.sin(2 * np.pi * freq * t) + 0.25 * np.sin(2 * np.pi * 2 * freq * t) * np.exp(-t * 3)
    tine = 0.12 * np.sin(2 * np.pi * 7.02 * freq * t) * np.exp(-t * 18)
    trem = 1 + 0.12 * np.sin(2 * np.pi * 4.2 * t + rng.uniform(0, 6.28))
    return (body + tine) * np.exp(-t * 0.6) * trem * _env(n, 0.008, 0.25) * vel


def _pad(midi: float, n: int, rng, voices=(-7, 0, 7), harms=3) -> np.ndarray:
    t = np.arange(n) / SR
    out = np.zeros(n)
    for c in voices:
        f = _mtof(midi + c / 100)
        for h in range(1, harms + 1):
            out += np.sin(2 * np.pi * f * h * t + rng.uniform(0, 6.28)) / h ** 1.6
    return out / len(voices)


def _kick(vel: float) -> np.ndarray:
    n = int(0.4 * SR)
    t = np.arange(n) / SR
    f = 45 + 80 * np.exp(-t * 28)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 8) * _env(n, 0.001, 0.05) * vel


def _snare(vel: float, rng) -> np.ndarray:
    n = int(0.25 * SR)
    t = np.arange(n) / SR
    noise = _highpass(rng.standard_normal(n) * np.exp(-t * 20), 1800)
    tone = 0.5 * np.sin(2 * np.pi * 190 * t) * np.exp(-t * 30)
    return (0.6 * noise + tone) * _env(n, 0.001, 0.03) * vel


def _hat(vel: float, rng, length: float = 0.05) -> np.ndarray:
    n = int(length * SR)
    t = np.arange(n) / SR
    return _highpass(rng.standard_normal(n), 7000) * np.exp(-t * 70) * vel


# ── the built-in tracks ──────────────────────────────────────────────────────

def _t_piano() -> np.ndarray:
    """Đệm piano nhẹ — C–G–Am–F arpeggios, 72 bpm, 8 bars."""
    rng = np.random.default_rng(11)
    beat = 60 / 72
    bar = 4 * beat
    buf = np.zeros(int(round(8 * bar * SR)))
    prog = [(60, (0, 4, 7)), (55, (0, 4, 7)), (57, (0, 3, 7)), (53, (0, 4, 7))]
    pattern = (0, 2, 3, 4, 3, 2, 1, 2)
    for b in range(8):
        root, iv = prog[b % 4]
        t0 = b * bar
        _place(buf, int(t0 * SR), _piano(_mtof(root - 24), 3.4, 0.5, rng))
        _place(buf, int((t0 + 2 * beat) * SR), _piano(_mtof(root - 17), 2.6, 0.3, rng))
        tones = (root - 12, root - 12 + iv[1], root - 12 + iv[2], root, root + iv[1])
        for k, idx in enumerate(pattern):
            vel = (0.34 if k == 0 else 0.24) + rng.uniform(0, 0.06)
            _place(buf, int((t0 + k * beat / 2 + rng.uniform(0, 0.012)) * SR), _piano(_mtof(tones[idx]), 2.4, vel, rng))
        if b % 2 == 1:   # a soft high answer every other bar
            _place(buf, int((t0 + 3 * beat) * SR), _piano(_mtof(root + 12 + iv[2] - 12), 2.8, 0.16, rng))
    return _reverb(_lowpass(buf, 6000), 2.4, 0.32, seed=1)


def _t_ambient() -> np.ndarray:
    """Ambient sâu lắng — slow evolving pads, four chords of 8 s."""
    rng = np.random.default_rng(22)
    chord_len, xf = 8.0, 3.0
    chords = [(57, 64, 67, 71, 76), (53, 60, 64, 69, 72), (48, 55, 64, 67, 74), (55, 62, 67, 71, 74)]
    buf = np.zeros(int(chord_len * len(chords) * SR))
    n = int((chord_len + xf) * SR)
    r = int(xf * SR)
    env = np.ones(n)
    w = 0.5 - 0.5 * np.cos(np.pi * np.arange(r) / r)
    env[:r], env[-r:] = w, w[::-1]
    t = np.arange(n) / SR
    for i, ch in enumerate(chords):
        sig = sum(_pad(m, n, rng) * (1 + 0.15 * np.sin(2 * np.pi * 0.11 * t + rng.uniform(0, 6.28))) for m in ch) / len(ch)
        sig = sig + 0.35 * np.sin(2 * np.pi * _mtof(ch[0] - 24) * t)
        _place(buf, int((i * chord_len - xf / 2) * SR), sig * env)
    return _reverb(_lowpass(buf, 2200), 4.5, 0.45, seed=2, damp=3500)


def _t_lofi() -> np.ndarray:
    """Lo-fi thư giãn — Dm7–G7–Cmaj7–Am7, 80 bpm, swing, vinyl crackle."""
    rng = np.random.default_rng(33)
    beat = 60 / 80
    bar = 4 * beat
    bars = 8
    buf = np.zeros(int(round(bars * bar * SR)))
    prog = [(62, (0, 3, 7, 10)), (55, (0, 4, 7, 10)), (60, (0, 4, 7, 11)), (57, (0, 3, 7, 10))]
    swing = 0.09 * beat
    for b in range(bars):
        root, iv = prog[b % 4]
        t0 = b * bar
        for k, (at, vel) in enumerate(((0.0, 0.32), (2.5, 0.2))):
            for j, i in enumerate(iv):
                _place(buf, int((t0 + at * beat + j * 0.012) * SR), _rhodes(_mtof(root - 12 + i), (bar if k == 0 else 1.5 * beat), vel, rng))
        for at, d, m in ((0, 1.4, 0), (1.5, 0.45, 0), (2.5, 1.2, 7)):
            nb = int(d * beat * SR)
            tt = np.arange(nb) / SR
            f = _mtof(root - 24 + m)
            bass = (np.sin(2 * np.pi * f * tt) + 0.2 * np.sin(4 * np.pi * f * tt)) * _env(nb, 0.01, 0.08) * 0.55
            _place(buf, int((t0 + at * beat) * SR), bass)
        for at in (0, 2.5):
            _place(buf, int((t0 + at * beat) * SR), _kick(0.8))
        for at in (1, 3):
            _place(buf, int((t0 + at * beat + 0.01) * SR), _snare(0.32, rng))
        for e in range(8):
            off = e * beat / 2 + (swing if e % 2 else 0)
            _place(buf, int((t0 + off) * SR), _hat(0.12 + rng.uniform(0, 0.06), rng))
    crackle = np.zeros(len(buf))
    pops = rng.integers(0, len(buf), int(len(buf) / SR * 6))
    crackle[pops] = rng.uniform(-1, 1, len(pops))
    crackle = _highpass(crackle, 2500) * 0.5 + _lowpass(rng.standard_normal(len(buf)), 4000) * 0.004
    return _reverb(_lowpass(buf, 4200), 1.6, 0.16, seed=3) + crackle


def _t_upbeat() -> np.ndarray:
    """Sôi động nhẹ — plucked 16th arpeggios, G–D–Em–C, 112 bpm."""
    rng = np.random.default_rng(44)
    beat = 60 / 112
    bar = 4 * beat
    bars = 8
    buf = np.zeros(int(round(bars * bar * SR)))
    prog = [(67, (0, 4, 7)), (62, (0, 4, 7)), (64, (0, 3, 7)), (60, (0, 4, 7))]
    pattern = (0, 1, 2, 3, 2, 1, 2, 3, 0, 1, 2, 3, 4, 3, 2, 1)
    for b in range(bars):
        root, iv = prog[b % 4]
        t0 = b * bar
        tones = (root - 12, root - 12 + iv[1], root - 12 + iv[2], root, root + iv[1])
        for k, idx in enumerate(pattern):
            vel = (0.3 if k % 4 == 0 else 0.2) + rng.uniform(0, 0.05)
            _place(buf, int((t0 + k * beat / 4) * SR), _pluck(_mtof(tones[idx]), 0.6, vel, rng))
        n = int(bar * SR)
        pad = sum(_pad(root - 12 + i, n, rng, voices=(-5, 5), harms=2) for i in iv) / 3 * 0.35
        _place(buf, int(t0 * SR), pad * _env(n, 0.3, 0.3))
        for q in range(4):
            _place(buf, int((t0 + q * beat) * SR), _kick(0.55))
            _place(buf, int((t0 + q * beat + beat / 2) * SR), _hat(0.14, rng, 0.04))
        for q in (1, 3):
            _place(buf, int((t0 + q * beat) * SR), _snare(0.22, rng))
        nb = int(bar * SR)
        tt = np.arange(nb) / SR
        _place(buf, int(t0 * SR), np.sin(2 * np.pi * _mtof(root - 24) * tt) * _env(nb, 0.01, 0.1) * 0.4)
    return _reverb(_lowpass(buf, 7000), 1.3, 0.2, seed=4)


def _t_rain() -> np.ndarray:
    """Tiếng mưa — shaped noise + droplets, 30 s."""
    rng = np.random.default_rng(55)
    n = 30 * SR
    f = np.fft.rfftfreq(n, 1 / SR)
    mag = 1 / np.maximum(f, 20) ** 0.75
    mag *= 1 / np.sqrt(1 + (250 / np.maximum(f, 1)) ** 4) / np.sqrt(1 + (f / 9000) ** 4)
    rumble = 2.5 / np.maximum(f, 20) ** 1.6 / np.sqrt(1 + (f / 180) ** 6)
    spec = (mag + rumble) * np.exp(1j * rng.uniform(0, 2 * np.pi, len(f)))
    spec[0] = 0
    x = np.fft.irfft(spec, n)
    x /= np.sqrt(np.mean(x ** 2))
    t = np.arange(n) / SR
    x *= 1 + 0.18 * np.sin(2 * np.pi * 3 * t / 30) + 0.08 * np.sin(2 * np.pi * 7 * t / 30 + 1)
    drops = np.zeros(n)
    m = int(0.02 * SR)
    tt = np.arange(m) / SR
    for _ in range(420):
        f0 = rng.uniform(1800, 5200)
        d = np.sin(2 * np.pi * (f0 + 2500 * tt) * tt) * np.exp(-tt * rng.uniform(180, 320)) * rng.uniform(0.3, 1.0)
        _place(drops, int(rng.integers(0, n)), d)
    return x + drops * 1.6


