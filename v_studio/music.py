"""Background music ("Nhạc nền"): a small built-in library synthesised on the
machine (no samples, no licences — every track is generated by the code below
and loops seamlessly) plus the user's own tracks, and a mixer that lays a track
under a voice with automatic ducking.

Files under ``~/.vstudio/music/``:

    builtin/<id>-v<N>.flac   cache of a generated track
    user/index.json          [{id, name, duration, sr, created}]
    user/<id>.flac           an imported track (mono, loudness-normalised)

    GET    /api/music                  {tracks: [{id, name, mood, desc, builtin, duration}]}
    GET    /api/music/{id}/preview     WAV (first 30 s) for the page's <audio>
    POST   /api/music                  multipart(file, name) → track
    DELETE /api/music/{id}             a user track
    POST   /api/mix                    multipart(file=voice WAV, track, volume, duck, duck_depth, intro, outro)
                                       → raw PCM s16le mono (X-Sample-Rate)
"""
